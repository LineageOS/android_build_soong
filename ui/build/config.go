type BuildAction uint

const (
	// Builds all of the modules and their dependencies of a specified directory, relative to the root
	// directory of the source tree.
	BUILD_MODULES_IN_A_DIRECTORY BuildAction = iota

	// Builds all of the modules and their dependencies of a list of specified directories. All specified
	// directories are relative to the root directory of the source tree.
	BUILD_MODULES_IN_DIRECTORIES

	// Build a list of specified modules. If none was specified, simply build the whole source tree.
	BUILD_MODULES
)

// checkTopDir validates that the current directory is at the root directory of the source tree.
func checkTopDir(ctx Context) {
	if _, err := os.Stat(srcDirFileCheck); err != nil {
		if os.IsNotExist(err) {
			ctx.Fatalf("Current working directory must be the source tree. %q not found.", srcDirFileCheck)
		}
		ctx.Fatalln("Error verifying tree state:", err)
	}
}

func loadEnvConfig(ctx Context, config *configImpl, bc string) error {
	if bc == "" {
		return nil
	}

	configDirs := []string{
		config.OutDir(),
		os.Getenv("ANDROID_BUILD_ENVIRONMENT_CONFIG_DIR"),
		envConfigDir,
	}
	for _, dir := range configDirs {
		cfgFile := filepath.Join(os.Getenv("TOP"), dir, fmt.Sprintf("%s.%s", bc, jsonSuffix))
		envVarsJSON, err := ioutil.ReadFile(cfgFile)
		if err != nil {
			continue
		}
		ctx.Verbosef("Loading config file %v\n", cfgFile)
		var envVars map[string]map[string]string
		if err := json.Unmarshal(envVarsJSON, &envVars); err != nil {
			fmt.Fprintf(os.Stderr, "Env vars config file %s did not parse correctly: %s", cfgFile, err.Error())
			continue
		}
		for k, v := range envVars["env"] {
			if os.Getenv(k) != "" {
				continue
			}
			config.environ.Set(k, v)
		}
		ctx.Verbosef("Finished loading config file %v\n", cfgFile)
		break
	}

	return nil
}

// NewDumpVarConfig does not parse any arguments.
func NewDumpVarConfig(ctx Context, args ...string) Config {
	return newConfig(ctx, true)
}

func NewConfig(ctx Context, args ...string) Config {
	return newConfig(ctx, false, args...)
}

func newConfig(ctx Context, isDumpVar bool, args ...string) Config {
	ret := &configImpl{
		environ:               OsEnvironment(),
		sandboxConfig:         &SandboxConfig{},
		ninjaWeightListSource: DEFAULT,
		isDumpVar:             isDumpVar,
	}
	wd, err := os.Getwd()
	if err != nil {
		ctx.Fatalln("Failed to get working directory:", err)
	}

	// If ResolveSoongEnvVars did work, log it.
	for _, msg := range resolveSoongEnvVarsMsgs {
		ctx.Verbosef("%s\n", msg)
	}

	// Skip soong tests by default on Linux
	if runtime.GOOS == "linux" {
		ret.skipSoongTests = true
	}

	// Default matching ninja
	ret.parallel = runtime.NumCPU() + 2
	ret.keepGoing = 1

	ret.totalRAM = detectTotalRAM(ctx)
	ret.systemCpuInfo, err = metrics.NewCpuInfo(fs.OsFs)
	if err != nil {
		ctx.Fatalln("Failed to get cpuinfo:", err)
	}
	ret.systemMemInfo, err = metrics.NewMemInfo(fs.OsFs)
	if err != nil {
		ctx.Fatalln("Failed to get meminfo:", err)
	}
	ret.parseArgs(ctx, args)

	switch os.Getenv("SOONG_NINJA") {
	case "ninja":
		ret.ninjaCommand = NINJA_NINJA
	case "n2":
		ret.ninjaCommand = NINJA_N2
	case "siso":
		ret.ninjaCommand = NINJA_SISO
	case "ninjago":
		ret.ninjaCommand = NINJA_NINJAGO
	default:
		ret.ninjaCommand = NINJA_DEFAULT
	}

	// TODO(b/490207582): SISO doesn't work on older versions of mac os that our CI builders use
	if runtime.GOOS == "darwin" && ret.ninjaCommand == NINJA_SISO {
		ret.ninjaCommand = NINJA_NINJA
	}

	if value, ok := ret.environ.Get("SOONG_ONLY"); ok && !ret.skipKatiControlledByFlags {
		if value == "true" || value == "1" || value == "y" || value == "yes" {
			ret.soongOnlyRequested = true
			ret.skipKatiControlledByFlags = true
			ret.skipKati = true
			ret.skipKatiNinja = true
		} else {
			ret.skipKatiControlledByFlags = true
			ret.skipKati = false
			ret.skipKatiNinja = false
		}
	}

	if ret.environ.IsEnvTrue("SOONG_INCREMENTAL_ANALYSIS") {
		ret.incrementalBuildActions = true
		ret.incrementalBuildActionsSetInEnv = true
	} else if ret.environ.IsFalse("SOONG_INCREMENTAL_ANALYSIS") {
		ret.incrementalBuildActions = false
		ret.incrementalBuildActionsSetInEnv = true
	}

	if value, ok := ret.environ.Get("SOONG_PARTIAL_ANALYSIS"); ok {
		ret.partialAnalysisTargets = value
	}

	if ret.ninjaWeightListSource == HINT_FROM_SOONG {
		ret.environ.Set("SOONG_GENERATES_NINJA_HINT", "always")
	} else if ret.ninjaWeightListSource == DEFAULT {
		defaultNinjaWeightListSource := NINJA_LOG
		if _, err := os.Stat(filepath.Join(ret.OutDir(), ninjaLogFileName)); errors.Is(err, os.ErrNotExist) {
			ctx.Verboseln("$OUT/.ninja_log doesn't exist, use HINT_FROM_SOONG instead")
			defaultNinjaWeightListSource = HINT_FROM_SOONG
		} else {
			ctx.Verboseln("$OUT/.ninja_log exist, use NINJA_LOG")
		}
		ret.ninjaWeightListSource = defaultNinjaWeightListSource
		// soong_build generates ninja hint depending on ninja log existence.
		// Set it "depend" to avoid soong re-run due to env variable change.
		ret.environ.Set("SOONG_GENERATES_NINJA_HINT", "depend")
	}

	// Make sure OUT_DIR is set appropriately
	if outDir, ok := ret.environ.Get("OUT_DIR"); ok {
		ret.environ.Set("OUT_DIR", filepath.Clean(outDir))
	} else {
		outDir := "out"
		if baseDir, ok := ret.environ.Get("OUT_DIR_COMMON_BASE"); ok {
			outDir = filepath.Join(baseDir, filepath.Base(wd))
		}
		ret.environ.Set("OUT_DIR", outDir)
	}

	// loadEnvConfig needs to know what the OUT_DIR is, so it should
	// be called after we determine the appropriate out directory.
	bc := os.Getenv("ANDROID_BUILD_ENVIRONMENT_CONFIG")

	if bc != "" {
		if err := loadEnvConfig(ctx, ret, bc); err != nil {
			ctx.Fatalln("Failed to parse env config files: %v", err)
		}
		if !ret.canSupportRBE() {
			// Explicitly set USE_RBE env variable to false when we cannot run
			// an RBE build to avoid ninja local execution pool issues.
			ret.environ.Set("USE_RBE", "false")
		}
	}

	rbeValue, rbeOk := ret.environ.GetBool("USE_RBE")
	if rbeOk {
		// Normalize USE_RBE to "true" or "false", because product config and other
		// makefiles only support those values.
		ret.environ.SetBool("USE_RBE", rbeValue)
	}
	rewrapperValue, rewrapperOk := ret.environ.GetBool("USE_REWRAPPER")
	if rewrapperOk {
		// Normalize USE_REWRAPPER to "true" or "false", because product config and
		// other makefiles only support those values.
		ret.environ.SetBool("USE_REWRAPPER", rewrapperValue)
	}

	if ret.ninjaCommand != NINJA_SISO {
		// If we are not using Siso, force USE_REWRAPPER to be the same as USE_RBE.
		if rbeValue != rewrapperValue {
			if rbeOk {
				ret.environ.SetBool("USE_REWRAPPER", rbeValue)
			} else {
				ret.environ.Unset("USE_REWRAPPER")
			}
		}
	} else {
		// If we are using Siso, force USE_REWRAPPER=false when USE_RBE is not "true".
		// These are separate only for Siso.
		if !rbeValue && rewrapperValue {
			// If not using RBE, don't use rewrapper.
			ret.environ.Set("USE_REWRAPPER", "false")
		} else if rbeValue && !rewrapperOk {
			// Always have a value in USE_REWRAPPER when USE_RBE is true.
			ret.environ.SetBool("USE_REWRAPPER", ret.UseRewrapper())
		}
		// Otherwise, rbeValue is true and USE_REWRAPPER was already set.
	}

	// Siso specific default values.
	if ret.ninjaCommand == NINJA_SISO {
		// If SISO_CONFIG_DIR is not set, set it to the default directory.
		if value, ok := ret.environ.Get("SISO_CONFIG_DIR"); ok {
			ret.sisoConfigDir = value
		} else {
			ret.sisoConfigDir = DEFAULT_SISO_CONFIG_DIR
		}
	}

	if distDir, ok := ret.environ.Get("DIST_DIR"); ok {
		ret.distDir = filepath.Clean(distDir)
	} else {
		ret.distDir = filepath.Join(ret.OutDir(), "dist")
	}

	ret.setupSandboxConfig(ctx, ret.environ.AsMap())

	if os.Getenv("GENERATE_SOONG_DEBUG") == "true" {
		ret.moduleDebugFile, _ = filepath.Abs(shared.JoinPath(ret.SoongOutDir(), "soong-debug-info.json"))
	}

	if os.Getenv("GENERATE_INCREMENTAL_DEBUG") == "true" {
		ret.incrementalDebugFile, _ = filepath.Abs(shared.JoinPath(ret.SoongOutDir(), "incremental-debug-info.json"))
	}

	// If SOONG_USE_PARTIAL_COMPILE is set, make it one of "true" or the empty string.
	// This simplifies the generated Ninja rules, so that they only need to check for the empty string.
	value, ok := ret.environ.Get("SOONG_USE_PARTIAL_COMPILE")
	if ok {
		if value == "true" || value == "1" || value == "y" || value == "yes" {
			value = "true"
		} else {
			value = ""
		}
		ret.environ.Set("SOONG_USE_PARTIAL_COMPILE", value)
	}

	if !ret.runCIPDProxyServerControlledByFlags {
		if value, ok := ret.environ.Get("SOONG_RUN_CIPD_PROXY_SERVER"); ok {
			parsedVal, err := strconv.ParseBool(value)
			if err == nil {
				ret.runCIPDProxyServer = parsedVal
				if !ret.runCIPDProxyServer {
					ctx.Verbosef("SOONG_RUN_CIPD_PROXY_SERVER=%q, disabling proxy", value)
				}
			} else {
				ctx.Verbosef("SOONG_RUN_CIPD_PROXY_SERVER (%q) is not a valid boolean", value)
			}
		}
	}

	ret.environ.Unset(
		// We're already using it
		"USE_SOONG_UI",

		// We should never use GOROOT/GOPATH from the shell environment
		"GOROOT",
		"GOPATH",

		// These should only come from Soong, not the environment.
		"CLANG",
		"CLANG_CXX",
		"CCC_CC",
		"CCC_CXX",

		// Used by the goma compiler wrapper, but should only be set by
		// gomacc
		"GOMACC_PATH",

		// We handle this above
		"OUT_DIR_COMMON_BASE",

		// This is handled above too, and set for individual commands later
		"DIST_DIR",

		// Variables that have caused problems in the past
		"BASH_ENV",
		"CDPATH",
		"DISPLAY",
		"GREP_OPTIONS",
		"JAVAC",
		"LEX",
		"NDK_ROOT",
		"POSIXLY_CORRECT",

		// Drop make flags
		"MAKEFLAGS",
		"MAKELEVEL",
		"MFLAGS",

		// Set in envsetup.sh, reset in makefiles
		"ANDROID_JAVA_TOOLCHAIN",

		// Set by envsetup.sh, but shouldn't be used inside the build because envsetup.sh is optional
		"ANDROID_BUILD_TOP",
		"ANDROID_HOST_OUT",
		"ANDROID_PRODUCT_OUT",
		"ANDROID_HOST_OUT_TESTCASES",
		"ANDROID_TARGET_OUT_TESTCASES",
		"ANDROID_TOOLCHAIN",
		"ANDROID_TOOLCHAIN_2ND_ARCH",
		"ANDROID_DEV_SCRIPTS",
		"ANDROID_EMULATOR_PREBUILTS",
		"ANDROID_PRE_BUILD_PATHS",

		// We read it here already, don't let others share in the fun
		"GENERATE_SOONG_DEBUG",
		"INCREMENTAL_SOONG_DEBUG",

		// Use config.ninjaCommand instead.
		"SOONG_NINJA",

		// Already incorporated into the config object
		"SOONG_ONLY",
	)

	// Tell python not to spam the source tree with .pyc files.
	ret.environ.Set("PYTHONDONTWRITEBYTECODE", "1")

	tmpDir := absPath(ctx, ret.TempDir())
	ret.environ.Set("TMPDIR", tmpDir)

	// Always set ASAN_SYMBOLIZER_PATH so that ASAN-based tools can symbolize any crashes
	symbolizerPath := filepath.Join("prebuilts/clang/host", ret.HostPrebuiltTag(),
		"llvm-binutils-stable/llvm-symbolizer")
	ret.environ.Set("ASAN_SYMBOLIZER_PATH", absPath(ctx, symbolizerPath))

	// Precondition: the current directory is the top of the source tree
	checkTopDir(ctx)

	srcDir := absPath(ctx, ".")
	if strings.ContainsRune(srcDir, ' ') {
		ctx.Println("You are building in a directory whose absolute path contains a space character:")
		ctx.Println()
		ctx.Printf("%q\n", srcDir)
		ctx.Println()
		ctx.Fatalln("Directory names containing spaces are not supported")
	}

	ret.metricsUploader = GetMetricsUploader(srcDir, ret.environ)

	if outDir := ret.OutDir(); strings.ContainsRune(outDir, ' ') {
		ctx.Println("The absolute path of your output directory ($OUT_DIR) contains a space character:")
		ctx.Println()
		ctx.Printf("%q\n", outDir)
		ctx.Println()
		ctx.Fatalln("Directory names containing spaces are not supported")
	}

	if distDir := ret.RealDistDir(); strings.ContainsRune(distDir, ' ') {
		ctx.Println("The absolute path of your dist directory ($DIST_DIR) contains a space character:")
		ctx.Println()
		ctx.Printf("%q\n", distDir)
		ctx.Println()
		ctx.Fatalln("Directory names containing spaces are not supported")
	}

	ConfigJavaEnvironment(ctx, ret)

	// b/286885495, https://bugzilla.redhat.com/show_bug.cgi?id=2227130: some versions of Fedora include patches
	// to unzip to enable zipbomb detection that incorrectly handle zip64 and data descriptors and fail on large
	// zip files produced by soong_zip.  Disable zipbomb detection.
	ret.environ.Set("UNZIP_DISABLE_ZIPBOMB_DETECTION", "TRUE")

	outDir := ret.OutDir()
	buildDateTimeFile := filepath.Join(outDir, "build_date.txt")
	if buildDateTime, ok := ret.environ.Get("BUILD_DATETIME"); ok && buildDateTime != "" {
		ret.buildDateTime = buildDateTime
	} else {
		ret.buildDateTime = strconv.FormatInt(time.Now().Unix(), 10)
	}

	ret.environ.Set("BUILD_DATETIME_FILE", buildDateTimeFile)

	if _, ok := ret.environ.Get("BUILD_USERNAME"); !ok {
		username := "unknown"
		if u, err := user.Current(); err == nil {
			username = u.Username
		} else {
			ctx.Println("Failed to get current user:", err)
		}
		ret.environ.Set("BUILD_USERNAME", username)
	}
	ret.environ.Set("PWD", wd)

	if ret.UseRBE() {
		for k, v := range getRBEVars(ctx, Config{ret}) {
			ret.environ.Set(k, v)
		}
	}
	ret.updateSisoConfigVars(map[string]string{})

	// BUILD_NUMBER should be set to the source control value that
	// represents the current state of the source code.  E.g., a
	// perforce changelist number or a git hash.  Can be an arbitrary string
	// (to allow for source control that uses something other than numbers),
	// but must be a single word and a valid file name.
	//
	// If no BUILD_NUMBER is set, create a useful "I am an engineering build"
	// value.  Make it start with a non-digit so that anyone trying to parse
	// it as an integer will probably get "0". This value used to contain
	// a timestamp, but now that more dependencies are tracked in order to
	// reduce the importance of `m installclean`, changing it every build
	// causes unnecessary rebuilds for local development.
	buildNumber, ok := ret.environ.Get("BUILD_NUMBER")
	var distFileNameTag string
	if ok {
		distFileNameTag = buildNumber
	} else {
		var username string
		if username, ok = ret.environ.Get("BUILD_USERNAME"); !ok {
			ctx.Fatalln("Missing BUILD_USERNAME")
		}
		buildNumber = fmt.Sprintf("eng.%.6s", username)
		distFileNameTag = username
	}

	ret.buildNumber = buildNumber
	ret.distFileNameTag = distFileNameTag

	c := Config{ret}
	storeConfigMetrics(ctx, c)
	return c
}

// Update or create the config variables for Siso.
//
// This is called in newConfig() to ensure that siso_config parses.
// It is then called in dumpMakeVars() to set values based on product config.
func (config *configImpl) updateSisoConfigVars(makeVars map[string]string) {
	if config.SisoStringVars == nil {
		config.SisoStringVars = make(map[string]string)
	}
	for _, k := range sisoStringVars {
		// If the variable is not found, we want to set it to the empty string.
		config.SisoStringVars[k] = makeVars[k]
	}
	if config.IsActionSandboxedBuild() {
		config.SisoStringVars["nsjail_path"] = config.PrebuiltBuildTool("nsjail")
	}
	config.SisoBoolVars = map[string]bool{
		"use_rbe":      config.UseRBE(),
		"use_reclient": config.UseRewrapper(),
	}
}

func ConfigJavaEnvironment(ctx Context, config *configImpl) {
	// Configure Java-related variables, including adding it to $PATH
	java8Home := filepath.Join("prebuilts/jdk/jdk8", strings.Replace(config.HostPrebuiltTag(), "linux-arm64", "linux-x86", 1))
	java21Home := filepath.Join("prebuilts/jdk/jdk21", config.HostPrebuiltTag())
	java25Home := filepath.Join("prebuilts/jdk/jdk25", config.HostPrebuiltTag())
	javaHome := func() string {
		if override, ok := config.environ.Get("OVERRIDE_ANDROID_JAVA_HOME"); ok {
			return override
		}
		if toolchain11, ok := config.environ.Get("EXPERIMENTAL_USE_OPENJDK11_TOOLCHAIN"); ok && toolchain11 != "true" {
			ctx.Fatalln("The environment variable EXPERIMENTAL_USE_OPENJDK11_TOOLCHAIN is no longer supported. An OpenJDK 21 toolchain is now the global default.")
		}
		if toolchain17, ok := config.environ.Get("EXPERIMENTAL_USE_OPENJDK17_TOOLCHAIN"); ok && toolchain17 != "true" {
			ctx.Fatalln("The environment variable EXPERIMENTAL_USE_OPENJDK17_TOOLCHAIN is no longer supported. An OpenJDK 21 toolchain is now the global default.")
		}
		if toolchain21, ok := config.environ.Get("EXPERIMENTAL_USE_OPENJDK21_TOOLCHAIN"); ok && toolchain21 != "true" {
			ctx.Fatalln("The environment variable EXPERIMENTAL_USE_OPENJDK21_TOOLCHAIN is no longer supported. An OpenJDK 21 toolchain is now the global default.")
		}
		if config.useJdk25 {
			return java25Home
		}
		return java21Home
	}()
	absJavaHome := absPath(ctx, javaHome)

	config.configureLocale(ctx)

	newPath := []string{filepath.Join(absJavaHome, "bin")}
	if path, ok := config.environ.Get("PATH"); ok && path != "" {
		newPath = append(newPath, path)
	}

	config.environ.Set("JAVA_HOME", absJavaHome)
	config.environ.Set("ANDROID_JAVA_HOME", javaHome)
	config.environ.Set("ANDROID_JAVA8_HOME", java8Home)
	config.environ.Set("PATH", strings.Join(newPath, string(filepath.ListSeparator)))
}

