// Which builder are we using?
type ninjaCommandType int

const (
	_ = iota
	NINJA_NINJA
	NINJA_N2
	NINJA_SISO
	NINJA_NINJAGO
)

var NINJA_DEFAULT ninjaCommandType = NINJA_SISO

func (n ninjaCommandType) String() string {
	switch n {
	case NINJA_NINJA:
		return "ninja"
	case NINJA_N2:
		return "n2"
	case NINJA_SISO:
		return "siso"
	case NINJA_NINJAGO:
		return "ninjago"
	default:
		return fmt.Sprintf("%v", int(n))
	}
}

