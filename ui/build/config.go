func (c *configImpl) canSupportRBE() bool {
	// Only supported on linux
	if runtime.GOOS != "linux" {
		return false
	}

	// Do not use RBE with prod credentials in scenarios when stubby doesn't exist, since
	// its unlikely that we will be able to obtain necessary creds without stubby.
	authType, _ := c.rbeAuth()
	if !c.StubbyExists() && strings.Contains(authType, "use_google_prod_creds") {
		return false
	}
	if c.UseABFS() {
		return false
	}
	return true
}

func (c *configImpl) UseABFS() (useABFS bool) {
	c.useABFSMu.Lock()
	defer c.useABFSMu.Unlock()

	if c.useABFS != nil {
		return *c.useABFS
	}

	defer func() {
		c.useABFS = new(bool)
		*c.useABFS = useABFS
	}()

	if c.ninjaCommand == NINJA_NINJAGO {
		return true
	}

	if v, ok := c.environ.Get("NO_ABFS"); ok {
		v = strings.ToLower(strings.TrimSpace(v))
		if v == "true" || v == "1" {
			return false
		}
	}

	abfsBox := c.PrebuiltBuildTool("abfsbox")
	err := exec.Command(abfsBox, "hash", srcDirFileCheck).Run()
	return err == nil
}

func (c *configImpl) UseRBE() bool {
	// These alternate modes of running Soong do not use RBE / reclient.
	if c.JsonModuleGraph() {
		return false
	}

	if !c.canSupportRBE() {
		return false
	}

	v, _ := c.Environment().GetBool("USE_RBE")
	return v
}

